package main

import (
	"os"
	"strings"
	"testing"
)

// TestPackagingBundlesTailcat guards the packaging files that carry the
// bundled tailcat CLI and the owldrop:// URL scheme. `wails3 update
// build-assets` (run by scripts/bump-release.sh) regenerates some build
// files from templates; 0.11.0/0.11.1 shipped GTK4 deb/rpm packages without
// tailcat because nfpm.yaml was silently regenerated. bump-release.sh runs
// this test right after regenerating.
func TestPackagingBundlesTailcat(t *testing.T) {
	for file, wants := range map[string][]string{
		"build/linux/nfpm/owldrop.yaml":       {"/usr/local/lib/owldrop/tailcat", "owldrop-url.desktop", "${OWLDROP_VERSION}"},
		"build/linux/nfpm/nfpm-gtk3.yaml":     {"/usr/local/lib/owldrop/tailcat", "owldrop-url.desktop", "${OWLDROP_VERSION}"},
		"build/linux/Taskfile.yml":            {"nfpm/owldrop.yaml", "build:tailcat", "OWLDROP_VERSION"},
		"build/linux/owldrop-url.desktop":     {"x-scheme-handler/owldrop"},
		"build/darwin/Taskfile.yml":           {"build:tailcat:universal", "Contents/MacOS/tailcat"},
		"build/darwin/Info.plist":             {"<string>owldrop</string>"},
		"build/windows/Taskfile.yml":          {"buildtailcat", "ARG_TAILCAT_BINARY"},
		"build/windows/nsis/project.nsi":      {"ARG_TAILCAT_BINARY"},
		"build/windows/nsis/wails_tools.nsh":  {`CUSTOM_PROTOCOL_ASSOCIATE "owldrop"`},
		"build/windows/msix/app_manifest.xml": {`Protocol Name="owldrop"`},
		"Dockerfile":                          {"buildtailcat", "/usr/local/bin/tailcat"},
		"flake.nix":                           {"tailcatPkg", "x-scheme-handler/owldrop"},
	} {
		b, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		for _, w := range wants {
			if !strings.Contains(string(b), w) {
				t.Errorf("%s no longer contains %q (regenerated by wails3 update build-assets?)", file, w)
			}
		}
	}
	for _, f := range []string{"build/linux/Taskfile.yml"} {
		if b, _ := os.ReadFile(f); strings.Contains(string(b), "nfpm/nfpm.yaml") {
			t.Errorf("%s packages from the wails-managed nfpm.yaml; use nfpm/owldrop.yaml", f)
		}
	}
}
